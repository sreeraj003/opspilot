"""Stored business intents and SQL generation artifacts (Module 10).

* ``BusinessIntentRecord`` keeps the validated ``BusinessIntent`` that Module 09
  produced, so SQL generation can load the real intent by id instead of
  trusting an intent object sent by a client. Only the user who asked can use
  it, and only for ``AI_SQL_INTENT_MAX_AGE_MINUTES``.
* ``SQLGenerationRecord`` is one candidate query produced by the model. Its SQL
  is **untrusted**: the table enforces ``trust_level = 'untrusted'`` and
  ``security_status = 'awaiting_security_validation'``, so a stored query never
  becomes executable merely because it is persisted. The SQL security guard
  (Module 11) re-parses and authorizes it independently, matched by
  ``sql_sha256``. No prompt text is stored.
* ``SQLGenerationEvent`` is the append-only audit trail of generation attempts:
  ids, provider, model, latency, attempts, outcome and failure category. It
  never contains SQL, the question, prompts or credentials.
"""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import Boolean, CheckConstraint, ForeignKey, Index, Integer, SmallInteger, String, Text, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.database.base import Base
from app.models.base_model import UUIDPrimaryKeyMixin

INTENT_STATUSES = ("understood", "needs_clarification")
GENERATION_STATUSES = ("generated", "clarification_required", "generation_failed")
PRELIMINARY_VALIDATION_STATUSES = ("passed", "failed", "not_run")
SQL_DIALECTS = ("postgres", "mysql", "tsql")
SECURITY_STATUSES = ("awaiting_security_validation",)
TRUST_LEVELS = ("untrusted",)
FAILURE_CATEGORIES = (
    "validation_failed",
    "unsafe_sql",
    "permission_denied",
    "malformed_output",
    "provider_error",
    "model_declined",
)
SQL_MAX_LENGTH = 20000


def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN (" + ", ".join(f"'{v}'" for v in values) + ")"


class BusinessIntentRecord(Base):
    __tablename__ = "business_intents"
    __table_args__ = (
        CheckConstraint(_in("status", INTENT_STATUSES), name="status_valid"),
        CheckConstraint("jsonb_typeof(intent) = 'object'", name="intent_is_object"),
        CheckConstraint("schema_version >= 1", name="schema_version_positive"),
        Index("ix_business_intents_user_created", "user_id", "created_at"),
        {"comment": "Validated business intents from question understanding, owned by the asking user."},
    )

    # The intent id generated by Module 09 (``BusinessIntent.intent_id``).
    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    schema_source_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("schema_sources.id", ondelete="CASCADE"))
    schema_version: Mapped[int] = mapped_column(Integer)
    status: Mapped[str] = mapped_column(String(32))
    policy_revision: Mapped[int] = mapped_column(Integer)
    # ``BusinessIntent.model_dump(mode="json")``: validated data only, never SQL or prompts.
    intent: Mapped[dict[str, Any]] = mapped_column(JSONB)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())

    def __repr__(self) -> str:
        return f"BusinessIntentRecord(id={self.id!s}, status={self.status!r})"


class SQLGenerationRecord(UUIDPrimaryKeyMixin, Base):
    __tablename__ = "sql_generations"
    __table_args__ = (
        CheckConstraint(_in("generation_status", GENERATION_STATUSES), name="generation_status_valid"),
        CheckConstraint(_in("validation_status", PRELIMINARY_VALIDATION_STATUSES), name="validation_status_valid"),
        CheckConstraint(_in("dialect", SQL_DIALECTS), name="dialect_valid"),
        # Generated SQL is never trusted or approved here; only Module 11 may approve a query,
        # and it does so in its own records, never by changing these columns.
        CheckConstraint(_in("security_status", SECURITY_STATUSES), name="security_status_valid"),
        CheckConstraint(_in("trust_level", TRUST_LEVELS), name="trust_level_untrusted"),
        CheckConstraint(
            f"failure_category IS NULL OR {_in('failure_category', FAILURE_CATEGORIES)}", name="failure_category_valid"
        ),
        # SQL is present exactly when the status is "generated".
        CheckConstraint(
            "(generation_status = 'generated') = (generated_sql IS NOT NULL)", name="sql_present_when_generated"
        ),
        CheckConstraint(
            "generated_sql IS NULL OR (char_length(generated_sql) BETWEEN 1 AND "
            f"{SQL_MAX_LENGTH} AND sql_sha256 IS NOT NULL)",
            name="sql_length",
        ),
        CheckConstraint("generation_attempts >= 0", name="attempts_non_negative"),
        CheckConstraint("latency_ms >= 0", name="latency_non_negative"),
        CheckConstraint("schema_version >= 1", name="schema_version_positive"),
        CheckConstraint("jsonb_typeof(referenced_tables) = 'array'", name="referenced_tables_is_array"),
        CheckConstraint("jsonb_typeof(referenced_columns) = 'array'", name="referenced_columns_is_array"),
        CheckConstraint("jsonb_typeof(joins_used) = 'array'", name="joins_used_is_array"),
        CheckConstraint("jsonb_typeof(assumptions) = 'array'", name="assumptions_is_array"),
        CheckConstraint("jsonb_typeof(validation_issues) = 'array'", name="validation_issues_is_array"),
        Index("ix_sql_generations_user_created", "user_id", "created_at"),
        Index("ix_sql_generations_intent", "intent_id"),
        {"comment": "Untrusted candidate SQL produced from business intents. Never executable as stored."},
    )

    user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    schema_source_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("schema_sources.id", ondelete="SET NULL"))
    schema_version: Mapped[int] = mapped_column(Integer)
    # The originating intent (``business_intents.id``). Kept as a plain id as well, so the
    # reference survives if the stored intent is removed.
    intent_id: Mapped[uuid.UUID] = mapped_column()
    intent_record_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("business_intents.id", ondelete="SET NULL"))
    # Set for a manual regeneration: the generation it replaces.
    regenerated_from_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("sql_generations.id", ondelete="SET NULL"))
    dialect: Mapped[str] = mapped_column(String(16))
    generated_sql: Mapped[str | None] = mapped_column(Text)
    # SHA-256 of ``generated_sql`` exactly as stored: the identity Module 11 must approve.
    sql_sha256: Mapped[str | None] = mapped_column(String(64))
    generation_status: Mapped[str] = mapped_column(String(32))
    validation_status: Mapped[str] = mapped_column(String(16))
    security_status: Mapped[str] = mapped_column(
        String(40), default="awaiting_security_validation", server_default=text("'awaiting_security_validation'")
    )
    trust_level: Mapped[str] = mapped_column(String(16), default="untrusted", server_default=text("'untrusted'"))
    failure_category: Mapped[str | None] = mapped_column(String(32))
    provider: Mapped[str | None] = mapped_column(String(64))
    model_name: Mapped[str | None] = mapped_column(String(200))
    prompt_version: Mapped[str] = mapped_column(String(40))
    generation_attempts: Mapped[int] = mapped_column(SmallInteger, default=0)
    latency_ms: Mapped[int] = mapped_column(Integer, default=0)
    policy_revision: Mapped[int] = mapped_column(Integer, default=0)
    # Derived from parsing the SQL (never the model's own claims).
    referenced_tables: Mapped[list[str]] = mapped_column(JSONB, default=list, server_default=text("'[]'::jsonb"))
    referenced_columns: Mapped[list[str]] = mapped_column(JSONB, default=list, server_default=text("'[]'::jsonb"))
    joins_used: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, default=list, server_default=text("'[]'::jsonb"))
    assumptions: Mapped[list[str]] = mapped_column(JSONB, default=list, server_default=text("'[]'::jsonb"))
    explanation: Mapped[str | None] = mapped_column(Text)
    clarification_question: Mapped[str | None] = mapped_column(Text)
    permission_notes: Mapped[list[str]] = mapped_column(JSONB, default=list, server_default=text("'[]'::jsonb"))
    # Issue codes and our own messages from preliminary validation (never model text).
    validation_issues: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, default=list, server_default=text("'[]'::jsonb"))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())

    def __repr__(self) -> str:
        return f"SQLGenerationRecord(id={self.id!s}, status={self.generation_status!r})"


class SQLGenerationEvent(UUIDPrimaryKeyMixin, Base):
    __tablename__ = "sql_generation_events"
    __table_args__ = (
        CheckConstraint(_in("status", GENERATION_STATUSES), name="status_valid"),
        CheckConstraint(_in("validation_outcome", PRELIMINARY_VALIDATION_STATUSES), name="validation_outcome_valid"),
        CheckConstraint("latency_ms >= 0", name="latency_non_negative"),
        CheckConstraint("retry_count >= 0", name="retry_count_non_negative"),
        Index("ix_sql_generation_events_created_at", "created_at"),
        Index("ix_sql_generation_events_user_created", "user_id", "created_at"),
        {"comment": "One row per SQL generation request. Outcome metadata only: no SQL, prompt or secrets."},
    )

    request_id: Mapped[str | None] = mapped_column(String(128))
    generation_id: Mapped[uuid.UUID | None]
    user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    intent_id: Mapped[uuid.UUID | None]
    schema_source_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("schema_sources.id", ondelete="SET NULL"))
    schema_version: Mapped[int | None] = mapped_column(Integer)
    dialect: Mapped[str | None] = mapped_column(String(16))
    is_regeneration: Mapped[bool] = mapped_column(Boolean, default=False, server_default=text("false"))
    provider: Mapped[str | None] = mapped_column(String(64))
    model: Mapped[str | None] = mapped_column(String(200))
    latency_ms: Mapped[int] = mapped_column(Integer, default=0)
    retry_count: Mapped[int] = mapped_column(SmallInteger, default=0)
    status: Mapped[str] = mapped_column(String(32))
    validation_outcome: Mapped[str] = mapped_column(String(16))
    failure_category: Mapped[str | None] = mapped_column(String(32))
    # Issue codes only (for example ["unknown_column"]).
    details: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict, server_default=text("'{}'::jsonb"))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())

    def __repr__(self) -> str:
        return f"SQLGenerationEvent(status={self.status!r})"
